"""Generate the paper's LaTeX tables directly from artifact JSON, so no number is typed by hand."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2];OUT=Path(__file__).resolve().parent
MODELS=[('alpamayo15','Alpamayo-1.5'),('alpamayo_r1','Alpamayo-R1'),('alpamayo2','Alpamayo-2')]
SAMPLERS=[('euler4_t1.0','$E_4$'),('shrink4_t1.0','Shrink$_4$'),('euler10_t1.0','$E_{10}$'),('shrink10_t1.0','Shrink$_{10}$'),('heun3_t1.0','Heun-3'),('heun5_t1.0','Heun-5')]


def num(x,digits=2):
    """Typeset a number with a true minus sign and no signed zero."""
    text=f'{x:.{digits}f}'
    if float(text)==0:text=f'{0:.{digits}f}'
    return text.replace('-','$-$')


def ci(x):
    """Interval bound in points: two decimals near zero so that the sign stays visible."""
    return num(x,2) if abs(x)<0.1 else num(x,1)


def matched_table():
    stats=json.loads((ROOT/'artifacts/paper_numbers_v4_20261026/summary.json').read_text())
    rows=[]
    for key,label in MODELS:
        model=stats['models'][key];first=True
        for sampler,name in SAMPLERS:
            if sampler not in model:continue
            e=model[sampler];ade=e['ade1'];flip=e['flip']
            mark='' if e['in_range'] else '$^\\dagger$'
            cells=[label if first else '',name,num(e['tau_eff'][0])+mark,
                num(ade['reference']),num(ade['sampler']),num(ade['matched']),
                num(100*flip['sampler'],1),num(100*flip['matched'],1),
                f"{num(100*flip['residual'][0],1)}\\,{{\\scriptsize[{ci(100*flip['residual'][1])},\\,{ci(100*flip['residual'][2])}]}}"]
            rows.append(' & '.join(cells)+r' \\');first=False
        rows.append(r'\midrule')
    body='\n    '.join(rows[:-1])
    return rf"""\begin{{table*}}[t]
  \caption{{\textbf{{Euler samplers land on the explicit-temperature curve; Heun samplers do not.}} For each sampler $S$ we report the reference solver at $\tau{{=}}1$ ($\Aref$), the sampler, and the reference solver at the sampler's effective temperature ($A_{{\taueff}}$). Flips are decision changes relative to $\Aref$ under the same noise; the last column is the flip residual $S-A_{{\taueff}}$ with a 95\% interval from a bootstrap over clips. Shrink$_k$ is a control with no integrator: each $\Aref$ sample moved linearly toward $E_1$ to $E_k$'s spread. {stats['clips']} PhysicalAI-AV test clips $\times$ 6 seeds per model.}}
  \label{{tab:matched}}
  \centering\small\setlength{{\tabcolsep}}{{5pt}}
  \begin{{tabular}}{{@{{}}llccccccc@{{}}}}
    \toprule
    & & & \multicolumn{{3}}{{c}}{{ADE$_1$ (m)}} & \multicolumn{{3}}{{c}}{{Decision flips (\%)}} \\
    \cmidrule(lr){{4-6}}\cmidrule(l){{7-9}}
    Model & Sampler $S$ & $\taueff$ & $\Aref$ & $S$ & $A_{{\taueff}}$ & $S$ & $A_{{\taueff}}$ & $S-A_{{\taueff}}$ \\
    \midrule
    {body}
    \bottomrule
  \end{{tabular}}
\end{{table*}}
"""


def contraction_table():
    stats=json.loads((ROOT/'artifacts/paper_numbers_v4_20261026/summary.json').read_text())
    g=json.loads((ROOT/'artifacts/gaussian_contraction_v1_20261026/summary.json').read_text())
    rows=[]
    for sampler,name in [('euler4_t1.0','$E_4$'),('euler10_t1.0','$E_{10}$'),('heun5_t1.0','Heun-5')]:
        cells=[name]
        for key,_ in MODELS:
            e=stats['models'][key].get(sampler)
            cells.append(f"{num(e['contraction']['median'])} ({100*e['contraction']['fraction_below_one']:.0f}\\%)" if e else '--')
        k={'euler4_t1.0':'4','euler10_t1.0':'10'}.get(sampler)
        cells.append(num(g['steps'][k]['predicted_median']) if k else '--')
        rows.append(' & '.join(cells)+r' \\')
    body='\n    '.join(rows)
    return rf"""\begin{{table}}[t]
  \caption{{\textbf{{Euler samplers contract toward the conditional mean; Heun does not.}} Median ratio of each sample's distance to the one-step mean $E_1$ over the reference sample's distance, from the same noise (share of samples with ratio $<1$ in parentheses), {stats['clips']} clips $\times$ 6 seeds. Gaussian: the closed-form factor of \cref{{eq:contraction}} from Alpamayo-1.5's conditional action variance (median over a separate sample of 200 clips in action space; it does not predict the per-clip ranking).}}
  \label{{tab:contraction}}
  \centering\footnotesize\setlength{{\tabcolsep}}{{3pt}}
  \begin{{tabular}}{{@{{}}lcccc@{{}}}}
    \toprule
    Sampler & Alpamayo-1.5 & Alpamayo-R1 & Alpamayo-2 & Gaussian \\
    \midrule
    {body}
    \bottomrule
  \end{{tabular}}
\end{{table}}
"""


