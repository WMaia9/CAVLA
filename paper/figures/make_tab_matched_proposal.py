"""Proposal (presentation review round 4): single-column redesign of Table 1 (tab:matched).

Differences from tables/make_tables.py::matched_table (which is untouched):
  * A_1's ADE_1 is printed once per model, in a model sub-header row, instead of in every row;
    the model column disappears, so the table fits one column (\\columnwidth) at \\footnotesize.
  * Rows are grouped by role: Euler (the claim), Shrink_k (control: any contraction passes),
    Heun (control: the test can fail), separated by small vertical space; Shrink rows gray, Heun residuals bold.
  * Residuals carry an explicit sign (+/-), matching the text ("+16.5 points").
Writes figures/tab_matched_proposal.tex. Run from paper/:  python figures/make_tab_matched_proposal.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]; OUT = Path(__file__).resolve().parent
MODELS = [('alpamayo15', 'Alpamayo-1.5'), ('alpamayo_r1', 'Alpamayo-R1'), ('alpamayo2', 'Alpamayo-2')]
GROUPS = [[('euler4_t1.0', '$E_4$'), ('euler10_t1.0', '$E_{10}$')],
          [('shrink4_t1.0', 'Shrink$_4$'), ('shrink10_t1.0', 'Shrink$_{10}$')],
          [('heun3_t1.0', 'Heun-3'), ('heun5_t1.0', 'Heun-5')]]
CTRL = r'\color{black!55}'


def num(x, d=2, sign=False):
    t = f'{x:.{d}f}'
    if float(t) == 0: t = f'{0:.{d}f}'
    if sign and float(t) > 0: t = '+' + t
    return t.replace('-', '$-$')


def main():
    s = json.loads((ROOT / 'artifacts/paper_numbers_v2_20261026/summary.json').read_text())
    rows = []
    for key, label in MODELS:
        m = s['models'][key]
        ref = m['euler10_t1.0']['ade1']['reference']
        rows.append(rf'\multicolumn{{7}}{{@{{}}l}}{{\textbf{{{label}}} \enspace {{\scriptsize $\Aref$: ADE$_1$ {num(ref)}\,m}}}} \\')
        first_group = True
        for g, group in enumerate(GROUPS):
            present = [(c, n) for c, n in group if c in m]
            if not present: continue
            if not first_group: rows.append(r'\addlinespace[1.5pt]')
            first_group = False
            for c, n in present:
                e = m[c]; a = e['ade1']; f = e['flip']; r = f['residual']
                pre = CTRL if g == 1 else ''
                cells = [r'\quad ' + pre + n, num(e['tau_eff'][0]) + ('' if e['in_range'] else r'$^\dagger$'),
                         num(a['sampler']), num(a['matched']), num(100 * f['sampler'], 1), num(100 * f['matched'], 1),
                         num(100 * r[0], 1, sign=True) + r'\,{\tiny[' + num(100 * r[1], 1) + ',\\,' + num(100 * r[2], 1) + ']}']
                if g == 2: cells[-1] = r'\textbf{' + cells[-1].split(r'\,{\tiny')[0] + '}' + r'\,{\tiny' + cells[-1].split(r'\,{\tiny')[1]
                if pre: cells = [cells[0]] + [pre + x for x in cells[1:]]
                rows.append(' & '.join(cells) + r' \\')
        rows.append(r'\midrule')
    body = '\n    '.join(rows[:-1])
    tex = rf"""% Generated by figures/make_tab_matched_proposal.py (proposal; not yet used by main.tex).
\begin{{table}}[t]
  \caption{{\textbf{{Temperature reproduces the rates of Euler samplers and of a spread-matched shrinkage, but not of Heun.}}
  Each sampler $S$ against the reference solver at its effective temperature, $\At{{\taueff}}$.
  Flips: decision changes relative to $\Aref$ under the same noise; last column: flip residual
  $S-\At{{\taueff}}$ in points with a 95\% clip-bootstrap interval. Two controls follow the Euler rows:
  Shrink$_k$ (gray) moves each $\Aref$ sample linearly toward $E_1$ until the spread matches $E_k$'s;
  Heun-$k$ (bold residuals) uses $2k$ evaluations and fails the test. {s['clips']} clips $\times$ 6 seeds per model.}}
  \label{{tab:matched}}
  \centering\footnotesize\setlength{{\tabcolsep}}{{3.2pt}}
  \begin{{tabular}}{{@{{}}lcccccr@{{}}}}
    \toprule
    & & \multicolumn{{2}}{{c}}{{ADE$_1$ (m)}} & \multicolumn{{3}}{{c}}{{Decision flips (\%)}} \\
    \cmidrule(lr){{3-4}}\cmidrule(l){{5-7}}
    $S$ & $\taueff$ & $S$ & $\At{{\taueff}}$ & $S$ & $\At{{\taueff}}$ & $S-\At{{\taueff}}$ \\
    \midrule
    {body}
    \bottomrule
  \end{{tabular}}
\end{{table}}
"""
    (OUT / 'tab_matched_proposal.tex').write_text(tex); print('wrote', OUT / 'tab_matched_proposal.tex')


if __name__ == '__main__':
    main()
